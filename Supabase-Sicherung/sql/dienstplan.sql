-- Dienstplan-Einträge aus dem Excel-Import (siehe app/dienstplan_parser.py,
-- routers/dienstplan.py). Lesen dürfen alle drei Rollenstufen (jede:r soll
-- den Dienstplan sehen können), Importieren/Ändern/Löschen ist
-- Schichtleitung und Admin vorbehalten.

create table if not exists public.dienstplan (
  id bigint generated by default as identity primary key,
  datum date not null,
  mitarbeiter_name text not null,
  dienst_kategorie text,
  start_zeit text,
  end_zeit text,
  ist_krank boolean not null default false,
  ist_bulmorfahrer boolean not null default false,
  notiz text not null default '',
  quelle_datei text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists dienstplan_datum_idx on public.dienstplan(datum);

alter table public.dienstplan enable row level security;
revoke all on public.dienstplan from anon;
grant select, insert, update, delete on public.dienstplan to authenticated;

