-- ---------------------------------------------------------------------------
-- 1) dienstplan: mitarbeiter_id ergänzen
-- ---------------------------------------------------------------------------

alter table public.dienstplan
  add column if not exists mitarbeiter_id bigint;

create index if not exists dienstplan_mitarbeiter_id_idx on public.dienstplan(mitarbeiter_id);

-- ---------------------------------------------------------------------------
-- 2) mitarbeiter_ereignis (Mitarbeiter-Historie)
-- ---------------------------------------------------------------------------

create table if not exists public.mitarbeiter_ereignis (
  id bigint generated by default as identity primary key,
  event_at timestamptz not null default now(),
  mitarbeiter_id bigint,
  mitarbeiter_name text not null default '',
  ereignis_typ text not null,
  beschreibung text not null default '',
  bezug_typ text,
  bezug_id text,
  actor_username text not null default '',
  actor_role text not null default '',
  details jsonb
);

create index if not exists mitarbeiter_ereignis_mitarbeiter_id_idx on public.mitarbeiter_ereignis(mitarbeiter_id);
create index if not exists mitarbeiter_ereignis_event_at_idx on public.mitarbeiter_ereignis(event_at);

alter table public.mitarbeiter_ereignis enable row level security;
revoke all on public.mitarbeiter_ereignis from anon;
grant select, insert on public.mitarbeiter_ereignis to authenticated;

create policy "fkb_read_mitarbeiter_ereignis" on public.mitarbeiter_ereignis for select to authenticated
  using ((select auth.jwt()->>'email') in ('dpfkb@gmx.de', 'bauschke.info@icloud.com'));

create policy "fkb_insert_mitarbeiter_ereignis" on public.mitarbeiter_ereignis for insert to authenticated
  with check ((select auth.jwt()->>'email') in ('dpfkb@gmx.de', 'bauschke.info@icloud.com'));

-- ---------------------------------------------------------------------------
-- 3) benutzer_aktivitaet (Logfile je Benutzerkonto)
-- ---------------------------------------------------------------------------

create table if not exists public.benutzer_aktivitaet (
  id bigint generated by default as identity primary key,
  event_at timestamptz not null default now(),
  username text not null default '',
  rolle text not null default '',
  aktion text not null,
  bereich text not null default '',
  entity_typ text,
  entity_id text,
  entity_bezeichnung text not null default '',
  beschreibung text not null default '',
  details jsonb
);

create index if not exists benutzer_aktivitaet_username_idx on public.benutzer_aktivitaet(username);
create index if not exists benutzer_aktivitaet_event_at_idx on public.benutzer_aktivitaet(event_at);

alter table public.benutzer_aktivitaet enable row level security;
revoke all on public.benutzer_aktivitaet from anon;
grant select, insert on public.benutzer_aktivitaet to authenticated;

create policy "fkb_read_benutzer_aktivitaet" on public.benutzer_aktivitaet for select to authenticated
