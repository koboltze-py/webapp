-- Admin vorbehalten (serverseitig über require_schichtleitung erzwungen,
-- siehe routers/meldungen.py).

create table if not exists public.meldungen (
  id bigint generated by default as identity primary key,
  titel text not null,
  text text not null default '',
  autor text not null default '',
  angeheftet boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.meldungen enable row level security;
revoke all on public.meldungen from anon;
grant select, insert, update, delete on public.meldungen to authenticated;

-- HIER die E-Mail des dritten ("Mitarbeiter"-)Kontos eintragen, siehe
-- benutzer.sql und Supabase-Sicherung\config.json ("login_email_mitarbeiter").
create policy "fkb_read_meldungen" on public.meldungen for select to authenticated
  using ((select auth.jwt()->>'email') in (
    'dpfkb@gmx.de', 'bauschke.info@icloud.com', 'MITARBEITER-EMAIL-HIER-EINTRAGEN'
  ));

create policy "fkb_write_meldungen" on public.meldungen for all to authenticated
  using ((select auth.jwt()->>'email') in ('dpfkb@gmx.de', 'bauschke.info@icloud.com'))
  with check ((select auth.jwt()->>'email') in ('dpfkb@gmx.de', 'bauschke.info@icloud.com'));
