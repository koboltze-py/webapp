-- ---------------------------------------------------------------------------
-- 1) benutzer (Einzel-Logins)
-- ---------------------------------------------------------------------------

create table if not exists public.benutzer (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  anzeigename text not null default '',
  rolle text not null check (rolle in ('mitarbeiter','schichtleitung','admin')),
  aktiv boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.benutzer enable row level security;
revoke all on public.benutzer from anon;
grant select, insert, update on public.benutzer to authenticated;

create policy "fkb_read_benutzer" on public.benutzer for select to authenticated
  using ((select auth.jwt()->>'email') in (
    'dpfkb@gmx.de', 'bauschke.info@icloud.com', 'MITARBEITER-EMAIL-HIER-EINTRAGEN'
  ));

create policy "fkb_write_benutzer" on public.benutzer for insert to authenticated
  with check ((select auth.jwt()->>'email') = 'bauschke.info@icloud.com');

create policy "fkb_update_benutzer" on public.benutzer for update to authenticated
  using ((select auth.jwt()->>'email') = 'bauschke.info@icloud.com');


