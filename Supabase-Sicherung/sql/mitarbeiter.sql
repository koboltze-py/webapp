-- Personal-Stammdaten. Lesen dürfen alle drei Rollenstufen, Anlegen/Ändern/
-- Löschen ist Schichtleitung und Admin vorbehalten (zusätzlich serverseitig
-- über require_schichtleitung erzwungen, siehe routers/mitarbeiter.py).

create table if not exists public.mitarbeiter (
  id bigint generated by default as identity primary key,
  vorname text not null,
  nachname text not null,
  personalnummer text not null default '',
  funktion text not null default '',
  email text not null default '',
  telefon text not null default '',
  aktiv boolean not null default true,
  notizen text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.mitarbeiter enable row level security;
revoke all on public.mitarbeiter from anon;
grant select, insert, update, delete on public.mitarbeiter to authenticated;

-- HIER die E-Mail des dritten ("Mitarbeiter"-)Kontos eintragen, siehe
-- benutzer.sql und Supabase-Sicherung\config.json ("login_email_mitarbeiter").
create policy "fkb_read_mitarbeiter" on public.mitarbeiter for select to authenticated
  using ((select auth.jwt()->>'email') in (
    'dpfkb@gmx.de', 'bauschke.info@icloud.com', 'MITARBEITER-EMAIL-HIER-EINTRAGEN'
  ));

create policy "fkb_write_mitarbeiter" on public.mitarbeiter for all to authenticated
  using ((select auth.jwt()->>'email') in ('dpfkb@gmx.de', 'bauschke.info@icloud.com'))
  with check ((select auth.jwt()->>'email') in ('dpfkb@gmx.de', 'bauschke.info@icloud.com'));
