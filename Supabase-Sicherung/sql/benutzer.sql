-- Einmalig im SQL Editor des BESTEHENDEN Supabase-Projekts ausführen.
--
-- WICHTIG VORHER: In Supabase Auth (Dashboard -> Authentication -> Users)
-- ein drittes Konto für die Rollenstufe "Mitarbeiter" anlegen (E-Mail +
-- Passwort frei wählbar, z. B. mitarbeiter@fkb.local) und:
--   1. die E-Mail in Supabase-Sicherung\config.json unter
--      "login_email_mitarbeiter" eintragen,
--   2. das Passwort in backend\.env als TIER_SERVICE_PASSWORD_MITARBEITER
--      eintragen (zusätzlich TIER_SERVICE_PASSWORD_ADMIN /
--      TIER_SERVICE_PASSWORD_SCHICHTLEITUNG mit den Passwörtern der beiden
--      bestehenden Konten dpfkb@gmx.de / bauschke.info@icloud.com).
-- Unten in den Policies die E-Mail-Platzhalter ANPASSEN, bevor dieses
-- Skript ausgeführt wird.
--
-- Legt die Tabelle für die neuen Einzel-Logins an (Benutzername + eigenes
-- bcrypt-Passwort, siehe backend\app\security.py). Gelesen wird diese
-- Tabelle vom Backend selbst über das Mitarbeiter-Service-Konto (geringste
-- Rechte), damit ein Login-Versuch stattfinden kann, bevor die Person
-- überhaupt identifiziert ist. Ein Service-Role-Key wird NICHT verwendet.

create table if not exists public.benutzer (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  anzeigename text not null default '',
  rolle text not null check (rolle in ('mitarbeiter','schichtleitung','admin')),
  aktiv boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.benutzer enable row level security;
revoke all on public.benutzer from anon;
grant select, insert, update on public.benutzer to authenticated;

-- Lesen dürfen alle drei Rollenstufen-Konten (nötig für den Login-Check).
create policy "fkb_read_benutzer" on public.benutzer for select to authenticated
  using ((select auth.jwt()->>'email') in (
    'dpfkb@gmx.de', 'bauschke.info@icloud.com', 'MITARBEITER-EMAIL-HIER-EINTRAGEN'
  ));

-- Anlegen/Ändern von Logins ist Admin-Aufgabe (zusätzlich serverseitig in
-- routers/benutzer.py über require_admin erzwungen). HIER die E-Mail des
-- ADMIN-Kontos eintragen (nicht Disposition!) - welche der beiden
-- bestehenden E-Mails das ist, steht in Supabase-Sicherung\config.json
-- unter "login_email_admin".
create policy "fkb_write_benutzer" on public.benutzer for insert to authenticated
  with check ((select auth.jwt()->>'email') = 'ADMIN-EMAIL-HIER-EINTRAGEN');

create policy "fkb_update_benutzer" on public.benutzer for update to authenticated
  using ((select auth.jwt()->>'email') = 'ADMIN-EMAIL-HIER-EINTRAGEN');
