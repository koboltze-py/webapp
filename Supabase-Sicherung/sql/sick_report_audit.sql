-- Einmalig im SQL Editor des BESTEHENDEN Supabase-Projekts ausführen
-- (desselben Projekts, dessen sick_reports-Tabelle bereits die Krankmeldungen
-- aus der alten Netlify-Webapp enthält, siehe ..\..\Background\supabase.sql).
--
-- Legt das Änderungsprotokoll für die neue FastAPI-Webapp an. Der Zugriff
-- erfolgt - genau wie bei sick_reports - über die zwei bestehenden
-- Login-Konten (Disposition/Admin) samt Row-Level-Security. Ein
-- Service-Role-Key wird NICHT verwendet.

create table if not exists public.sick_report_audit (
  id bigint generated by default as identity primary key,
  event_at timestamptz not null default now(),
  report_id uuid,
  action text not null check (action in ('INSERT','UPDATE','DELETE')),
  actor_role text not null check (actor_role in ('admin','disposition')),
  old_data jsonb,
  new_data jsonb
);

create index if not exists sick_report_audit_report_id on public.sick_report_audit(report_id);

alter table public.sick_report_audit enable row level security;
revoke all on public.sick_report_audit from anon;
grant select, insert on public.sick_report_audit to authenticated;

-- Beide bestehenden Login-Konten dürfen das Änderungsprotokoll lesen und
-- neue Einträge schreiben (Ändern/Löschen bestehender Einträge ist bewusst
-- nicht vorgesehen - das Protokoll bleibt unveränderlich).
create policy "fkb_read_audit" on public.sick_report_audit for select to authenticated
  using ((select auth.jwt()->>'email') in ('dpfkb@gmx.de', 'bauschke.info@icloud.com'));

create policy "fkb_insert_audit" on public.sick_report_audit for insert to authenticated
  with check ((select auth.jwt()->>'email') in ('dpfkb@gmx.de', 'bauschke.info@icloud.com'));

